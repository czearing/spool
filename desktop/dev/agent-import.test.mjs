import assert from "node:assert/strict";
import test from "node:test";
import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { createHash } from "node:crypto";
import { createServer } from "vite";
import { chromium, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";

test("imports linked agents and creates blank agents directly in the editor", { timeout: 120000 }, async t => {
  const root = await mkdtemp(join(tmpdir(), "spool-import-browser-")), previous = { ...process.env };
  const projects = ["source", "target"].map(id => ({ id, name: id === "source" ? "Source" : "Target", root: join(root, id) }));
  let server, browser;
  t.after(async () => {
    await browser?.close(); await server?.close(); await rm(root, { recursive: true, force: true });
    for (const key of Object.keys(process.env)) if (!(key in previous)) delete process.env[key];
    Object.assign(process.env, previous);
  });
  process.env.SPOOL_DATA_DIR = root;
  await writeFile(join(root, "connections.json"), JSON.stringify({ SPOOL_PROJECTS_FILE: join(root, "projects.json"),
    SPOOL_RUNNERS_HOME: join(root, "runners"), SPOOL_RUNNERS_CONFIG: join(root, "runners", "missing.json") }));
  await writeFile(join(root, "projects.json"), JSON.stringify({ version: 1, projects }));
  for (const project of projects) for (const directory of ["agents", "controls", "queues/incoming", "queues/in_progress", "queues/completed", "queues/failed"])
    await mkdir(join(project.root, directory), { recursive: true });
  const original = "---\nmodel: source-model\n---\n# Designer\nResearch before recommending.\n";
  await writeFile(join(projects[0].root, "agents", "designer.md"), original);
  server = await createServer({ root: resolve(import.meta.dirname, ".."), server: { host: "127.0.0.1", port: 0 }, logLevel: "error" });
  await server.listen();
  const origin = `http://127.0.0.1:${server.httpServer.address().port}`;
  browser = await chromium.launch();
  const browserContext = await browser.newContext({ viewport: { width: 1280, height: 960 } });
  const page = await browserContext.newPage();
  await page.route("**/api/models", route => route.fulfill({ json: [] }));
  await page.goto(`${origin}/#/target`);
  await page.getByRole("button", { name: "Agents", exact: true }).click();
  await page.getByRole("button", { name: "Add agent", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Add agent" });
  await dialog.getByRole("textbox", { name: "Name", exact: false }).fill("new-draft");
  await dialog.getByRole("tab", { name: "New agent", exact: true }).focus();
  const library = page.waitForResponse(response => response.url().endsWith("/agent-import"));
  await page.keyboard.press("ArrowRight");
  const catalog = await library;
  assert.equal(catalog.status(), 200, await catalog.text());
  assert.equal((await catalog.json()).projects[0]?.agents[0], "designer", await catalog.text());
  await expect(dialog.getByRole("tab", { name: "Import from project" })).toHaveAttribute("aria-selected", "true");
  await dialog.getByRole("searchbox", { name: "Search agents", exact: true }).fill("no-match");
  await expect(dialog.getByRole("status")).toHaveText("No matching agents.");
  await dialog.getByRole("searchbox", { name: "Search agents", exact: true }).fill("Source");
  assert.equal(await dialog.getByRole("radio").count(), 1, await dialog.ariaSnapshot());
  await dialog.getByRole("radio", { name: "designer from Source" }).click();
  await expect(dialog.getByRole("region", { name: "Shared instructions preview" })).toContainText("Research before recommending.");
  await expect(dialog.locator("textarea, [contenteditable=true]")).toHaveCount(0);
  await dialog.getByRole("tab", { name: "New agent", exact: true }).click();
  await expect(dialog.getByRole("textbox", { name: "Name", exact: false })).toHaveValue("new-draft");
  await dialog.getByRole("tab", { name: "Import from project" }).click();
  await expect(dialog.getByRole("region", { name: "Shared instructions preview" })).toContainText("Research before recommending.");
  assert.deepEqual((await new AxeBuilder({ page }).include('[role="dialog"]').analyze()).violations, []);
  if (process.env.SPOOL_TEST_ARTIFACTS) await page.screenshot({ path: join(process.env.SPOOL_TEST_ARTIFACTS, "agent-import-desktop.png") });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await dialog.evaluate(element => element.scrollWidth > element.clientWidth), false);
  const action = await dialog.getByRole("button", { name: "Import agent", exact: true }).boundingBox();
  assert.ok(action && action.y + action.height <= 844, "Import action must remain visible without scrolling on mobile.");
  if (process.env.SPOOL_TEST_ARTIFACTS) await page.screenshot({ path: join(process.env.SPOOL_TEST_ARTIFACTS, "agent-import-mobile.png") });
  await writeFile(join(projects[1].root, "controls", "capabilities.json"),
    JSON.stringify({ sharedPromptsVersion: 1, updatedAt: new Date().toISOString() }));
  const imported = page.waitForResponse(response => response.url().endsWith("/agent-import") && response.request().method() === "POST");
  await dialog.getByRole("button", { name: "Import agent", exact: true }).click();
  assert.equal((await imported).status(), 201);
  await expect(dialog).toHaveCount(0);
  assert.equal(await readFile(join(projects[0].root, "agents", "designer.md"), "utf8"), original);
  const local = await readFile(join(projects[1].root, "agents", "designer.md"), "utf8");
  assert.match(local, /shared_prompt:/); assert.doesNotMatch(local, /Research before recommending/);
  assert.match(local, /This instance belongs to Target/);
  await page.setViewportSize({ width: 1280, height: 960 });
  await page.goto(`${origin}/#/target/agents/designer/prompt`);
  await page.getByRole("button", { name: "Project instructions", exact: true }).click();
  const context = page.getByRole("dialog", { name: "Project instructions" });
  await expect(context.getByRole("textbox")).toHaveValue(/This instance belongs to Target\./);
  await context.getByRole("textbox").fill("Private Target context.");
  await context.getByRole("button", { name: "Save instructions" }).click();
  await expect(context).toHaveCount(0);
  const sourceUrl = `${origin}/api/projects/source/agents/designer`;
  const document = await (await page.request.get(sourceUrl)).json();
  const saved = await page.request.put(sourceUrl, { headers: { Origin: origin }, data: { ...document, prompt: "Updated shared role" } });
  assert.equal(saved.status(), 200);
  const linked = await (await page.request.get(`${origin}/api/projects/target/agents/designer`)).json();
  assert.equal(linked.prompt, "Updated shared role");
  assert.equal((await page.request.delete(sourceUrl, { headers: { Origin: origin } })).status(), 409);
  assert.match(await readFile(join(projects[1].root, "agents", "designer.md"), "utf8"), /Private Target context/);
  const rejected = await page.request.post(`${origin}/api/projects/target/agent-import`, {
    headers: { Origin: "https://foreign.invalid" }, data: {} });
  assert.equal(rejected.status(), 403);
  let attempts = 0;
  await page.route("**/api/projects/target/agents", async route => {
    const input = route.request().postDataJSON();
    assert.deepEqual(input, { name: "new-draft", model: null, image: null, max_concurrent_runs: 1, prompt: "" });
    if (++attempts === 1) return route.fulfill({ status: 409, json: { error: "An agent with this name already exists." } });
    const content = "---\nmax_concurrent_runs: 1\n---\n";
    await writeFile(join(projects[1].root, "agents", "new-draft.md"), content);
    await route.fulfill({ status: 201, json: { name: input.name, description: "", model: null, image: null,
      defaultModel: "fixture-model", icon: "bot", maxConcurrentRuns: 1, revision: createHash("sha256").update(content).digest("hex") } });
  });
  let finishCatalog;
  const catalogPending = new Promise(resolve => { finishCatalog = resolve; });
  await page.route("**/api/models", async route => {
    await catalogPending;
    await route.fulfill({ json: [] });
  });
  t.after(() => finishCatalog());
  await page.reload();
  const add = page.getByRole("button", { name: "Add agent", exact: true });
  if (!await add.isVisible()) await page.getByRole("button", { name: "Agents", exact: true }).click();
  await add.click();
  await expect(dialog.locator("textarea, [contenteditable=true]")).toHaveCount(0);
  await expect(dialog.getByRole("button", { name: "Create agent", exact: true })).toBeDisabled();
  await dialog.getByRole("textbox", { name: "Name", exact: false }).fill("new-draft");
  await expect(dialog.getByRole("button", { name: "Create agent", exact: true })).toBeEnabled();
  if (process.env.SPOOL_TEST_ARTIFACTS) await page.screenshot({ path: join(process.env.SPOOL_TEST_ARTIFACTS, "agent-create-simple-desktop.png") });
  await dialog.getByRole("button", { name: "Create agent", exact: true }).click();
  await expect(dialog.getByRole("alert")).toHaveText("An agent with this name already exists.");
  await expect(dialog.getByRole("textbox", { name: "Name", exact: false })).toHaveValue("new-draft");
  await dialog.getByRole("button", { name: "Create agent", exact: true }).click();
  await expect(page).toHaveURL(`${origin}/#/target/agents/new-draft/prompt`);
  finishCatalog();
  const editor = page.getByRole("textbox", { name: "new-draft prompt", exact: true });
  await expect(editor).toHaveText("");
  await editor.fill("Instructions written after creation.");
  await expect.poll(() => readFile(join(projects[1].root, "agents", "new-draft.md"), "utf8"))
    .toContain("Instructions written after creation.");
  await page.reload();
  await expect(editor).toHaveText("Instructions written after creation.");
});
