test("project writes reject cross-origin and invalid requests without changing task or registry files", async ({ request, projectServer: server }) => {
  const before = await readFile(server.registry, "utf8");
  const task = join(server.bohemia, "queues", "completed", "A-1.json"), original = await readFile(task, "utf8");
  const data = { name: "Rejected", root: server.bookCook };
  expect((await request.post(`${server.url}/api/projects`, { data, headers: { Origin: "http://other.example" } })).status()).toBe(403);
  expect((await request.post(`${server.url}/api/projects`, { data: "{broken", headers: { Origin: server.url, "Content-Type": "application/json" } })).status()).toBe(400);
  expect((await request.post(`${server.url}/api/projects`, { data: "text", headers: { Origin: server.url, "Content-Type": "text/plain" } })).status()).toBe(415);
  expect((await request.post(`${server.url}/api/projects`, { data: {}, headers: { Origin: server.url } })).status()).toBe(400);
  expect(await readFile(server.registry, "utf8")).toBe(before); expect(await readFile(task, "utf8")).toBe(original);
});
test("Spool folder picker uses the selected absolute path when saving a project", async ({ page, projectServer: server }) => {
  await page.route("**/api/file-picker?kind=folder", (route) => route.fulfill({ json: { path: server.bookCook } }));
  await page.goto(server.url);
  await page.getByRole("button", { name: "Switch project, Bohemia" }).click();
  await page.getByRole("menuitem", { name: "Create project...", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Create project", exact: true });
  await dialog.getByRole("textbox", { name: /^Project name/ }).fill("Picked project");
  await dialog.getByRole("button", { name: "Browse for Spool folder", exact: true }).click();
  await expect(dialog.getByRole("textbox", { name: /^Spool folder/ })).toHaveValue(server.bookCook);
  await dialog.getByRole("button", { name: "Create project", exact: true }).click();
  await expect(page.getByRole("button", { name: "Switch project, Picked project" })).toBeVisible();
  const saved = JSON.parse(await readFile(server.registry, "utf8"));
  expect(saved.projects.at(-1).name).toBe("Picked project");
});
