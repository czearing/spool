import { test, expect, workItemTotal } from "./project-fixture";
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import AxeBuilder from "@axe-core/playwright";

test("creating a real project from the menu persists across server restarts and preserves Tasks", async ({ page, projectServer: server }) => {
  await page.goto(`${server.url}/bohemia/tasks`);
  await page.getByRole("button", { name: "Switch project, Bohemia" }).click();
  await page.getByRole("menuitem", { name: "Create project...", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Create project", exact: true });
  const name = dialog.getByRole("textbox", { name: /^Project name/ });
  await expect(name).toBeFocused();
  await name.fill("Recipe development");
  await dialog.getByRole("textbox", { name: /^Spool folder/ }).fill(server.bookCook);
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await dialog.getByRole("button", { name: "Create project", exact: true }).click();
  await expect(page.getByRole("button", { name: "Switch project, Recipe development" })).toBeVisible();
  await expect(page.locator("[data-work-item-id]")).toHaveCount(3);
  await expect(page).toHaveURL(/\/[a-f0-9-]+\/tasks$/);
  const target = page.url();
  const saved = JSON.parse(await readFile(server.registry, "utf8"));
  expect(saved.projects.map((project: { name: string }) => project.name)).toEqual(["Bohemia", "Recipe development"]);
  await server.restart(); await page.goto(target);
  await expect(page.getByRole("button", { name: "Switch project, Recipe development" })).toBeVisible();
  await expect(page.locator("[data-work-item-id]")).toHaveCount(3);
  await page.getByRole("link", { name: "Home", exact: true }).click(); await expect(workItemTotal(page)).toHaveText("3 work items");
});
test("creation reports invalid folders and duplicates without losing entered values or existing settings", async ({ page, projectServer: server }) => {
  const before = await readFile(server.registry, "utf8");
  await page.goto(`${server.url}/bohemia`);
  const trigger = page.getByRole("button", { name: "Switch project, Bohemia" });
  await trigger.click(); await page.getByRole("menuitem", { name: "Create project...", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Create project", exact: true });
  const name = dialog.getByRole("textbox", { name: /^Project name/ }), folder = dialog.getByRole("textbox", { name: /^Spool folder/ });
  const submit = dialog.getByRole("button", { name: "Create project", exact: true });
  await name.fill("Different"); await folder.fill(join(server.root, "missing")); await submit.click();
  await expect(dialog.getByRole("alert")).toContainText("must contain queues");
  await expect(name).toHaveValue("Different");
  await folder.fill(server.bohemia); await submit.click();
  await expect(dialog.getByRole("alert")).toContainText("already connected");
  await name.fill("Bohemia"); await folder.fill(server.bookCook); await submit.click();
  await expect(dialog.getByRole("alert")).toContainText("name already exists");
  expect(await readFile(server.registry, "utf8")).toBe(before);
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(trigger).toBeFocused();
});
