/// A real repository rather than a stub, because the checks being guarded read a real working tree.
/// Origin carries the repository name so clone selection accepts it; nothing is ever pushed.
const scratchRoots: string[] = [];
afterAll(() => { for (const root of scratchRoots) rmSync(root, { recursive: true, force: true }); });
async function scratchClone(): Promise<string> {
  const parent = join(tmpdir(), `gate-scratch-${Math.random().toString(36).slice(2)}`);
  scratchRoots.push(parent);
  const root = join(parent, "office-bohemia");
  await mkdir(root, { recursive: true });
  await Bun.$`git init -q -b gate-scratch ${root}`.quiet();
  await Bun.write(join(root, "a.txt"), "original");
  await Bun.$`git -C ${root} remote add origin https://example.invalid/office-bohemia`.quiet();
  await Bun.$`git -C ${root} add -A`.quiet();
  await Bun.$`git -C ${root} -c user.email=t@t -c user.name=t commit -qm seed`.quiet();
  return root;
}

