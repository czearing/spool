describe("every write path is gated", () => {
  // A gate is only as strong as its weakest path. `create` ran the checks and `update` did not,
  // which made update the route a change could take to reach Azure DevOps unchecked, while the
  // tool still reported itself as enforcing. This asserts the property structurally, so removing
  // the call from either path fails here rather than on a pull request months later.
  const source = readFileSync(join(import.meta.dir, "tools.ts"), "utf8");
  const body = (name: string) => {
    const start = source.indexOf(`async function ${name}(`);
    expect(start).toBeGreaterThan(-1);
    const next = source.indexOf("\nasync function ", start + 1);
    const end = source.indexOf("\nexport async function callTool", start + 1);
    return source.slice(start, Math.min(...[next, end].filter((i) => i > start)));
  };

  for (const path of ["create", "update"]) {
    test(`${path} runs the repository's checks before writing`, () => {
      const fn = body(path);
      expect(fn).toContain("await runGate(");
      expect(fn).toContain("if (!gate.ok) return toolResult(id, checksRejection(gate), true);");
    });

    test(`${path} refuses before touching the pull request`, () => {
      // Ordering matters as much as presence: checks that run after the write cannot prevent it.
      const fn = body(path);
      const gated = fn.indexOf("if (!gate.ok)");
      const writes = [fn.indexOf("createWithOrigin("), fn.indexOf("createPullRequest("), fn.indexOf("patchPullRequest(")].filter(
        (i) => i > -1,
      );
      expect(writes.length).toBeGreaterThan(0);
      for (const write of writes) expect(gated).toBeLessThan(write);
    });
  }
});

describe("the transport cannot go stale", () => {
  // An agent session holds one server process open for hours, and a process serves the code it
  // loaded at startup. A rule fixed on disk therefore reached nobody: a pull request was updated
  // with checks skipped a full day after the gating landed. The transport now runs each request in
  // a fresh process, which only works while the transport itself holds no rules to go stale.
  const transport = readFileSync(join(import.meta.dir, "index.ts"), "utf8");

  test("imports nothing that carries a rule", () => {
    // The worker is referenced as a path, not imported, so this file has no relative imports at all.
    expect([...transport.matchAll(/from\s+"\.[^"]*"/g)].map((m) => m[0])).toEqual([]);
  });

  test("answers tool requests from a newly spawned process", () => {
    expect(transport).toContain("spawn(process.execPath, [WORKER]");
    for (const method of ["tools/list", "tools/call"]) expect(transport).toContain(method);
  });

  test("gives the checks no deadline, since they take minutes by design", () => {
    expect(transport).not.toMatch(/timeout\s*:/);
  });

  test("keeps a waiting client informed instead of letting it time out", () => {
    // A client that hears nothing for minutes gives up with -32001 while the checks keep running,
    // and the agent reads that as a broken tool. The protocol's answer is a progress notification,
    // sent only when the caller supplied a token to correlate it with.
    expect(transport).toContain("notifications/progress");
    expect(transport).toContain("progressToken");
    const reporter = transport.slice(transport.indexOf("function progressReporter"));
    expect(reporter.indexOf("return () => {};")).toBeLessThan(reporter.indexOf("setInterval"));
    expect(transport).toContain("clearInterval");
  });
});

